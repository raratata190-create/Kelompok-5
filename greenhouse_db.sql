DELIMITER $$
CREATE TRIGGER `after_sensor_insert` AFTER INSERT ON `sensor_data` FOR EACH ROW BEGIN
    DECLARE alert_msg VARCHAR(255);
    
    -- LOW_SOIL (< 30%)
    IF NEW.soil_moisture < 30 THEN
        SET alert_msg = CONCAT('CRITICAL: Soil moisture too low! ', NEW.soil_moisture, '%');
        INSERT INTO alerts (alert_type, soil_moisture, message) 
        VALUES ('LOW_SOIL', NEW.soil_moisture, alert_msg);
    END IF;
    
    -- LOW_WATER (< 20%)
    IF NEW.water_level < 20 THEN
        SET alert_msg = CONCAT('CRITICAL: Water tank empty! ', NEW.water_level, '% (', NEW.distance, 'cm)');
        INSERT INTO alerts (alert_type, water_level, distance, message) 
        VALUES ('LOW_WATER', NEW.water_level, NEW.distance, alert_msg);
    END IF;
    
    -- CRITICAL (keduanya low)
    IF NEW.soil_moisture < 25 AND NEW.water_level < 15 THEN
        INSERT INTO alerts (alert_type, soil_moisture, water_level, message) 
        VALUES ('CRITICAL', NEW.soil_moisture, NEW.water_level, 'EMERGENCY: Both soil & water critical!');
    END IF;
END
$$
DELIMITER ;
DELIMITER $$
CREATE TRIGGER `update_daily_stats` AFTER INSERT ON `sensor_data` FOR EACH ROW BEGIN
    INSERT INTO system_stats (stat_date, total_readings, uptime_hours)
    SELECT 
        CURDATE(),
        COUNT(*) as total_readings,
        (COUNT(*) * 5 / 3600) as uptime_hours  -- 5 detik per reading
    FROM sensor_data 
    WHERE DATE(timestamp) = CURDATE()
    ON DUPLICATE KEY UPDATE
        total_readings = VALUES(total_readings),
        uptime_hours = VALUES(uptime_hours);
END
$$
DELIMITER ;

